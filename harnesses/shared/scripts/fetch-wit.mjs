#!/usr/bin/env node
/*
 * Fetch a harness's WIT with the repository's registry map and enforce its
 * committed lock.
 *
 * Every package comes from the registries in wit/wkg-registries.toml, pinned
 * by the component's committed wkg.lock: WASI from wasi.dev, and
 * cosmonic:agent from its published package on ghcr.io.
 *
 * COSMONIC_WIT points cosmonic:agent at a local WIT tree instead (for example
 * this repository's own wit/), to try an interface change before it is
 * published. Overridden packages are not recorded in wkg.lock, so the lock
 * check cannot see them: an override is for local testing only, and is refused
 * when CI=true.
 *
 * REGEN_LOCK=1 regenerates the locks for review instead of enforcing them.
 *
 *   node harnesses/shared/scripts/fetch-wit.mjs <component-dir>...
 */

import { existsSync, readFileSync, readdirSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { isMain, repoRoot, run, runMain } from './build-helpers.mjs';

// The local-testing override of cosmonic:agent, if any.
export function localWit() {
    let wit = process.env.COSMONIC_WIT;
    if (!wit) {
        return undefined;
    }
    if (['true', '1'].includes(process.env.CI)) {
        throw new Error(
            'COSMONIC_WIT points the WIT fetch at local packages, which wkg.lock does not record; overrides are for local testing only and are refused in CI',
        );
    }
    wit = realpathSync(wit);
    if (!existsSync(join(wit, 'cosmonic-agent')) || !statSync(join(wit, 'cosmonic-agent')).isDirectory()) {
        throw new Error(`no cosmonic-agent/ in ${wit}`);
    }
    console.log(`  using local interfaces from ${wit} (not the published packages)`);
    return wit;
}

export function fetchWit(dirs) {
    if (!dirs?.length) {
        throw new Error('usage: node harnesses/shared/scripts/fetch-wit.mjs <component-dir>...');
    }
    const wit = localWit();
    const config = join(repoRoot, 'wit/wkg-registries.toml');

    for (const input of dirs) {
        const dir = realpathSync(input);
        if (!existsSync(join(dir, 'wit/world.wit'))) {
            throw new Error(`no wit/world.wit in ${dir}`);
        }
        const lock = join(dir, 'wkg.lock');
        const regenerate = process.env.REGEN_LOCK === '1';
        if (!regenerate && !existsSync(lock)) {
            throw new Error(`no wkg.lock in ${dir}; run with REGEN_LOCK=1 and commit it`);
        }
        const before = regenerate ? undefined : readFileSync(lock);
        if (wit) {
            writeFileSync(
                join(dir, 'wkg.toml'),
                [
                    '# Generated by harnesses/shared/scripts/fetch-wit.mjs; gitignored.',
                    '[overrides]',
                    `"cosmonic:agent" = { path = ${JSON.stringify(join(wit, 'cosmonic-agent'))} }`,
                    '',
                ].join('\n'),
            );
        } else {
            rmSync(join(dir, 'wkg.toml'), { force: true });
        }
        rmSync(join(dir, 'wit/deps'), { recursive: true, force: true });
        if (regenerate) {
            rmSync(lock, { force: true });
        }
        try {
            run(process.env.WKG || 'wkg', ['fetch', '--config', config], { cwd: dir });
            if (!existsSync(lock)) {
                throw new Error(`wkg fetch did not write ${lock}`);
            }
            if (before && !before.equals(readFileSync(lock))) {
                throw new Error(
                    `wkg fetch changed ${lock}. Restored the committed lock; if intended, re-run with REGEN_LOCK=1 and commit the new lock`,
                );
            }
        } catch (error) {
            if (before) {
                writeFileSync(lock, before);
            }
            throw error;
        }
        console.log(`  fetched WIT for ${dir}: ${readdirSync(join(dir, 'wit/deps')).join(' ')}`);
    }
}

if (isMain(import.meta.url)) {
    await runMain(() => fetchWit(process.argv.slice(2)));
}
